# Хук UserPromptSubmit озвучки Claude Code (подключается через `. путь/к/этому/файлу`).
# Python запускается, только если в сообщении есть «озвуч…» или «молч…»: обычное сообщение
# проходит почти мгновенно, а не ждёт ~0,4 с, пока загрузится Python. `read` встроен в bash,
# поэтому на обычном пути не запускается ни одного процесса.
# Кириллица в JSON может прийти и как есть, и как \uXXXX — второй вид ловят шаблоны с `?u04…`.
IFS= read -r -d '' __speak_in
case "$__speak_in" in
  *озвуч*|*Озвуч*|*ОЗВУЧ*|*молч*|*Молч*|*МОЛЧ*|\
  *?u04[13][eE]?u0437?u0432?u0443?u0447*|*?u04[13][cC]?u043[eE]?u043[bB]?u0447*)
    printf '%s' "$__speak_in" | "$(dirname "${BASH_SOURCE[0]}")/../.venv/Scripts/python.exe" -m voice_input.claude_hook prompt ;;
esac
